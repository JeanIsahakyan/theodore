//! Writes `cloud/src/gen/fleet.ts`. Run from the workspace root:
//! `cargo run -p theodore-fleet-protocol --bin export-ts`.

fn main() {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "cloud/src/gen/fleet.ts".into());
    if let Some(dir) = std::path::Path::new(&out).parent() {
        std::fs::create_dir_all(dir).expect("create output dir");
    }
    let ts = specta_typescript::Typescript::default()
        .export(&theodore_fleet_protocol::types(), specta_serde::Format)
        .expect("export TS");
    let mut clean: String = ts.lines().map(|l| format!("{}\n", l.trim_end())).collect();
    while clean.ends_with("\n\n") {
        clean.pop();
    }
    let header =
        "// Generated by `cargo run -p theodore-fleet-protocol --bin export-ts`. Do not edit.\n";
    std::fs::write(&out, format!("{header}{clean}")).expect("write TS");
    println!("wrote {out}");
}
