//! Writes `cloud/src/gen/fleet.ts`. Run from the workspace root:
//! `cargo run -p theodore-fleet-protocol --bin export-ts`.

fn main() {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "cloud/src/gen/fleet.ts".into());
    if let Some(dir) = std::path::Path::new(&out).parent() {
        std::fs::create_dir_all(dir).expect("create output dir");
    }
    let ts = specta_typescript::Typescript::default()
        .export(&theodore_fleet_protocol::types(), specta_serde::Format)
        .expect("export TS");
    let mut clean: String = ts.lines().map(|l| format!("{}\n", l.trim_end())).collect();
    while clean.ends_with("\n\n") {
        clean.pop();
    }
    clean.push_str(&codes_ts());
    let header =
        "// Generated by `cargo run -p theodore-fleet-protocol --bin export-ts`. Do not edit.\n";
    std::fs::write(&out, format!("{header}{clean}")).expect("write TS");
    println!("wrote {out}");

    // Shared signing vectors: other clients (the phone/web app) check their
    // ed25519 + domain-tag code against exactly what Rust produces.
    let vectors = std::path::Path::new(&out).with_file_name("fleet-vectors.json");
    std::fs::write(&vectors, vectors_json()).expect("write vectors");
    println!("wrote {}", vectors.display());
}

/// `codes` as a TS object: refusal codes by their Rust name.
fn codes_ts() -> String {
    let mut out = String::from(
        "\n/** Refusal codes (docs/fleet.md), by their Rust name. */\nexport const FLEET_CODES = {\n",
    );
    for (name, code) in theodore_fleet_protocol::codes::ALL {
        out.push_str(&format!("\t{name}: \"{code}\",\n"));
    }
    out.push_str("} as const;\n");
    out
}

fn vectors_json() -> String {
    use theodore_fleet_protocol::{
        DeviceKey, Domain, FleetMode, NONCE_BYTES, RemoteOp, RemoteRequest, SignedEnvelope, b64,
        sign_hello,
    };
    let seed = [7u8; 32];
    let key = DeviceKey::from_seed_for_vectors(&seed).expect("seed key");
    let nonce = [9u8; NONCE_BYTES];
    let req = RemoteRequest {
        req_id: "req_vector".into(),
        origin_device: "dev_00000000-0000-4000-8000-000000000001".into(),
        target_device: "dev_00000000-0000-4000-8000-000000000002".into(),
        target_key: "target-key".into(),
        issued_at_ms: 1_700_000_000_000,
        op: RemoteOp::Send {
            space: "rs_vector".into(),
            text: "hello".into(),
            mode: Some(FleetMode::Edit),
            agent: Some("claude".into()),
            model: Some("opus".into()),
            effort: Some("high".into()),
            attachments: vec![],
        },
    };
    let env = SignedEnvelope::seal(&req, &key);
    let v = serde_json::json!({
        "seed_b64": b64(&seed),
        "public_key": key.public_key(),
        "hello": {
            "nonce_b64": b64(&nonce),
            "signature": sign_hello(&key, &b64(&nonce)).expect("hello"),
        },
        "request": {
            "body": env.body,
            "signature": env.signature,
        },
        "tags": {
            "hello": String::from_utf8_lossy(Domain::Hello.tag()),
            "request": String::from_utf8_lossy(Domain::Request.tag()),
            "event": String::from_utf8_lossy(Domain::Event.tag()),
            "ask": String::from_utf8_lossy(Domain::Ask.tag()),
            "reply": String::from_utf8_lossy(Domain::Reply.tag()),
            "delegate": String::from_utf8_lossy(Domain::Delegate.tag()),
            "confirm": String::from_utf8_lossy(Domain::Confirm.tag()),
        },
        "blobs": blob_vectors(),
    });
    serde_json::to_string_pretty(&v).expect("vectors serialize") + "\n"
}

/// Blob crypto vectors (docs/fleet.md "Files (blobs)"): fixed recipient
/// seed, ephemeral secret, nonce prefix and blob id; the plaintext is
/// `generator` applied to `0..size` (`"i*31 mod 251"`: byte i is
/// `(i * 31) % 251`), so 4 MiB isn't embedded. Expected: the recipient's
/// X25519 key, the blob key, every chunk's nonce, AAD and ciphertext
/// SHA-256, and the `BlobRef` as it goes on the wire.
fn blob_vectors() -> serde_json::Value {
    use sha2::{Digest, Sha256};
    use theodore_fleet_protocol::blob::{
        CHUNK_BYTES, INFO, SealParams, blob_key, chunk_aad, chunk_nonce, seal_blob_with,
        x25519_public_from_ed25519, x25519_secret_from_ed25519_seed,
    };
    use theodore_fleet_protocol::{DeviceKey, b64, unb64};

    let recipient_seed = [11u8; 32];
    let recipient = DeviceKey::from_seed_for_vectors(&recipient_seed).expect("seed key");
    let recipient_pk: [u8; 32] = unb64(&recipient.public_key())
        .expect("b64")
        .try_into()
        .expect("32 bytes");
    let recipient_x = x25519_public_from_ed25519(&recipient_pk).expect("a point");
    let recipient_x_sk = x25519_secret_from_ed25519_seed(&recipient_seed);
    let pattern = |size: usize| -> Vec<u8> { (0..size).map(|i| ((i * 31) % 251) as u8).collect() };

    let cases = [
        ("empty", 0usize, "empty.bin", "application/octet-stream"),
        ("ten bytes", 10, "ten.txt", "text/plain"),
        (
            "4 MiB + 3: two chunks",
            CHUNK_BYTES + 3,
            "big.bin",
            "application/octet-stream",
        ),
    ];
    let list: Vec<serde_json::Value> = cases
        .iter()
        .enumerate()
        .map(|(n, (title, size, name, mime))| {
            let k = n as u8 + 1;
            let params = SealParams {
                blob_id: hex::encode([0x10 * k; 16]),
                eph_sk: [0x20 + k; 32],
                nonce_prefix: [0x30 + k; 16],
            };
            let (eph_pk, key) = blob_key(&params.eph_sk, &recipient_x);
            let plain = pattern(*size);
            let (r, chunks) =
                seal_blob_with(&params, &recipient.public_key(), &plain, name, mime).expect("seal");
            let chunk_rows: Vec<serde_json::Value> = chunks
                .iter()
                .enumerate()
                .map(|(i, c)| {
                    let i = i as u32;
                    serde_json::json!({
                        "index": i,
                        "nonce_b64": b64(&chunk_nonce(&params.nonce_prefix, i)),
                        "aad_hex": hex::encode(chunk_aad(&r.blob_id, i, r.chunks)),
                        "ciphertext_len": c.len(),
                        "ciphertext_sha256": hex::encode(Sha256::digest(c)),
                    })
                })
                .collect();
            serde_json::json!({
                "title": title,
                "plaintext": { "size": size, "generator": "i*31 mod 251" },
                "eph_secret_b64": b64(&params.eph_sk),
                "eph_public_key_b64": b64(&eph_pk),
                "key_b64": b64(&key),
                "ref": r,
                "chunks": chunk_rows,
            })
        })
        .collect();
    serde_json::json!({
        "info": String::from_utf8_lossy(INFO),
        "chunk_bytes": CHUNK_BYTES,
        "recipient": {
            "seed_b64": b64(&recipient_seed),
            "public_key": recipient.public_key(),
            "x25519_public_key_b64": b64(&recipient_x),
            "x25519_secret_b64": b64(&recipient_x_sk),
        },
        "cases": list,
    })
}
